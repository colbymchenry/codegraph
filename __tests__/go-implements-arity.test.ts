let root = '';
let cg: CodeGraph;

beforeAll(async () => {
  root = fs.mkdtempSync(path.join(os.tmpdir(), 'cg-go-implements-arity-'));
  for (const [rel, content] of Object.entries(FILES)) {
    fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
    fs.writeFileSync(path.join(root, rel), content);
  }
  cg = await CodeGraph.init(root, { index: true });
}, 120_000);

afterAll(() => {
  cg?.destroy();
  if (root) fs.rmSync(root, { recursive: true, force: true });
});

const meta = (e: Edge): Record<string, unknown> => (e.metadata ?? {}) as Record<string, unknown>;
const pkg = (n: Node | null): string => `${path.posix.dirname(n?.filePath ?? '?')}.${n?.name}`;

/** The one non-import node with this name in this file. */
function one(name: string, file: string): Node {
  const found = cg.getNodesByName(name).filter((n) => n.filePath === file && n.kind !== 'import');
  expect(found, `${name} in ${file}`).toHaveLength(1);
  return found[0]!;
}

/** Every synthesized struct → interface edge, as `pkg.Struct -> pkg.Interface`. */
function goImplements(): string[] {
  const structs = cg.getNodesByKind('struct').filter((n) => n.language === 'go');
  return cg
    .getOutgoingEdgesFrom(structs.map((n) => n.id), ['implements'])
    .filter((e) => meta(e).synthesizedBy === 'go-implements')
    .map((e) => `${pkg(cg.getNode(e.source))} -> ${pkg(cg.getNode(e.target))}`)
    .sort();
}

/** Where a call through an interface method lands: its interface-impl targets. */
function dispatch(iface: string, file: string, method: string): string[] {
  const m = cg
    .getOutgoingEdgesFrom([one(iface, file).id], ['contains'])
    .map((e) => cg.getNode(e.target))
    .find((n) => n?.name === method)!;
  return cg
    .getOutgoingEdgesFrom([m.id], ['calls'])
    .filter((e) => meta(e).synthesizedBy === 'interface-impl')
    .map((e) => cg.getNode(e.target)!.qualifiedName)
    .sort();
}

describe('Go implicit satisfaction checks parameter and result counts', () => {
  it('links only the structs whose methods take and return as many values', () => {
    expect(goImplements()).toEqual([
      'api.UnimplementedKVServer -> api.KVClient',
      'api.UnimplementedKVServer -> api.KVServer',
      'api.UnimplementedKVServer -> server.RaftKV',
      'api.kVClient -> api.KVClient',
      'generic.tagger -> generic.Tagger',
      'generic.walker -> generic.Visitor',
      'rafthttp.Transport -> rafthttp.peerGetter',
      'server.kvServer -> api.KVClient',
      'server.kvServer -> api.KVServer',
      'server.kvServer -> server.RaftKV',
      'server.rangeCloser -> server.RaftKV',
      'storage.boltStore -> storage.Putter',
      'storage.bridgeDialer -> storage.Dialer',
      'storage.memAppender -> storage.Appender',
      'testutil.tmpDir -> testutil.Closer',
      'xds.grpcTransportBuilder -> xds.TransportBuilder',
    ]);
  });

  it('dispatches a call through an interface only to methods Go could reach', () => {
    expect(dispatch('peerGetter', 'rafthttp/http.go', 'Get')).toEqual(['Transport::Get']);
    expect(dispatch('Closer', 'testutil/closer.go', 'Close')).toEqual(['tmpDir::Close']);
    // The generated client ranges with call options; RaftKV doesn't take them.
    expect(dispatch('RaftKV', 'server/kv.go', 'Range')).toEqual([
      'UnimplementedKVServer::Range',
      'kvServer::Range',
      'rangeCloser::Range',
    ]);
  });

  it('keeps a struct that fails the counts out of the per-interface cap', () => {
    const builders = cg
      .getIncomingEdgesTo([one('TransportBuilder', 'xds/transport.go').id], ['implements'])
      .filter((e) => meta(e).synthesizedBy === 'go-implements')
      .map((e) => pkg(cg.getNode(e.source)));
    expect(builders).toEqual(['xds.grpcTransportBuilder']);
  });
});

describe('a gRPC client interface reaches the servers of its service', () => {
  it('links the client stub and every server, unary and streaming RPCs alike', () => {
    for (const rpc of ['Range', 'List', 'Watch']) {
      expect(dispatch('KVClient', 'api/kv_grpc.pb.go', rpc), rpc).toEqual([
        `UnimplementedKVServer::${rpc}`,
        `kVClient::${rpc}`,
        `kvServer::${rpc}`,
      ]);
    }
    expect(
      cg
        .getIncomingEdgesTo([one('KVClient', 'api/kv_grpc.pb.go').id], ['implements'])
        .map((e) => pkg(cg.getNode(e.source)))
        .sort()
    ).toEqual(['api.UnimplementedKVServer', 'api.kVClient', 'server.kvServer']);
  });

  it('leaves out a wrapper with methods of the same names and other shapes', () => {
    const wrapper = cg
      .getOutgoingEdgesFrom([one('kv', 'client/kv.go').id], ['implements'])
      .map((e) => pkg(cg.getNode(e.target)));
    expect(wrapper).toEqual([]);
  });

  it('takes server arities only for an interface whose every method is a client call', () => {
    const rangers = cg
      .getIncomingEdgesTo([one('closingRanger', 'server/kv.go').id], ['implements'])
      .map((e) => pkg(cg.getNode(e.source)));
    expect(rangers).toEqual([]);
  });
});

describe('goSignatureArity', () => {
  it.each([
    ['()', '0/0'],
    ['() error', '0/1'],
    ['(s string) (int)', '1/1'],
    ['(a, b int) (n int, err error)', '2/2'],
    ['(ctx context.Context, opts ...grpc.CallOption) (grpc.BidiStreamingClient[WatchRequest, WatchResponse], error)', '2/2'],
    ['(fn func(a, b int) (int, error), m map[string][]int)', '2/0'],
    ['(p Pair[K, V]) func() (int, error)', '1/1'],
    ['(\n\tref uint64, // the series, or 0 (new)\n\tv float64, /* sample, value */\n) (uint64, error)', '2/2'],
    ['(v struct {\n\tA, B int `json:"a,omitempty" yaml:"(b)"`\n}) string', '1/1'],
    ["(r rune) bool", '1/1'],
  ])('reads %j as %s', (signature, arity) => {
    expect(goSignatureArity(signature)).toBe(arity);
  });

  it.each([[undefined], [''], ['(a int'], ['[T any](x T)'], ['(a int) (b int'], ['(a int) (b int) c']])(
    'gives up on %j',
    (signature) => {
      expect(goSignatureArity(signature)).toBeNull();
    }
  );
});
