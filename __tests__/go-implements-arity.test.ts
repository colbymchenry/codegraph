/**
 * Go's implicit interface satisfaction (#584) wants every method's signature
 * identical, but goImplementsEdges matched method NAMES only:
 *
 *   type peerGetter interface { Get(id types.ID) Peer }      // etcd rafthttp
 *   func (c *Cache) Get(ctx context.Context, key string,
 *       opts ...clientv3.OpOption) (*clientv3.GetResponse, error)
 *
 * so etcd's watch cache "implemented" peerGetter, and every interface with a
 * common method name (Get, Close, Build, Watch) collected structs that could
 * never satisfy it — enough of them, at grpc-go's TransportBuilder, to fill
 * the per-interface cap before the real implementer was reached. The pass now
 * also wants each method's parameter and result counts, read off the stored
 * signature text.
 *
 * One shape is kept on purpose: a server struct and the generated gRPC CLIENT
 * interface of its service (`kvServer` and `KVClient`). That pair never
 * satisfies Go, but its interface-impl edges are the bridge a client's call
 * crosses to reach the handler serving it, so a client interface also takes
 * its RPCs' server arities.
 */
