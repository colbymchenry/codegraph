function loadInitial(): LocaleCode {
  if (typeof window !== 'undefined') {
    try {
      const saved = window.localStorage.getItem(STORAGE_KEY);
      if (saved === 'en' || saved === 'zh-CN') return saved;
    } catch {
      // Storage refused (private mode): default to English.
    }
  }
  return 'en';
}

let currentLocale: LocaleCode = loadInitial();

export function getCurrentLocale(): LocaleCode {
  return currentLocale;
}

export function setCurrentLocale(value: LocaleCode): void {
  currentLocale = value;
  if (typeof window !== 'undefined') {
    try {
      window.localStorage.setItem(STORAGE_KEY, value);
    } catch {
      // Storage refused (private mode): the choice is in-memory for this visit.
    }
  }
}

/** Look up a message for the current locale; interpolation via `{key}`. */
export function t(key: string, params?: Record<string, string | number>): string {
  const table = messages[currentLocale] ?? messages.en;
  const raw = Object.hasOwn(table, key) ? table[key]! : (messages.en[key] ?? key);
  let text = Array.isArray(raw) ? raw[0] : raw;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}

/** Look up a message that ships as a [singular, plural] pair. */
export function tPair(key: string): [string, string] {
  const table = messages[currentLocale] ?? messages.en;
  const raw = Object.hasOwn(table, key) ? table[key]! : (messages.en[key] ?? key);
  return Array.isArray(raw) ? raw : [raw, raw];
}

/**
 * Returns the count followed by the appropriately inflected noun: English adds
 * an `s` to the singular when the count is not one (or uses the explicit
 * plural), while Chinese keeps the noun unchanged because it has no plural form.
 */
export function plural(count: number, one: string, many = `${one}s`): string {
  if (currentLocale === 'zh-CN') return `${count} ${one}`;
  return `${count} ${count === 1 ? one : many}`;
}

/** Whether the current language inflects plurals (English does; Chinese does not). */
export function hasPluralInflection(): boolean {
  return currentLocale !== 'zh-CN';
}
