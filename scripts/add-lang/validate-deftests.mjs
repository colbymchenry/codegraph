#!/usr/bin/env node
// Validate that every (deftest NAME …) form in a corpus is extracted as a
// node in the codegraph index. Counts source deftests (via the same
// preprocessing the extractor uses, then walking the parse tree the SAME way
// the extractor would identify a top-level def* form) and compares against
// the indexed function nodes.
//
// Usage: node scripts/add-lang/validate-deftests.mjs <repo>

import { readFileSync, statSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { LispExtractor } from '../../dist/extraction/lisp-extractor.js';

const repo = process.argv[2];
if (!repo) { console.error('usage: validate-deftests.mjs <repo>'); process.exit(1); }

function* walk(dir) {
  for (const e of readdirSync(dir)) {
    if (e === '.git' || e === 'node_modules' || e === '.codegraph') continue;
    const full = join(dir, e);
    let st; try { st = statSync(full); } catch { continue; }
    if (st.isDirectory()) yield* walk(full);
    else if (/\.(lisp|lsp|cl|asd|el)$/i.test(e)) yield full;
  }
}

// Count `(deftest NAME` occurrences in raw source via a tolerant regex — the
// ground-truth "how many tests are defined". deftest names can contain almost
// any char (dots, digits, escapes), so match up to the next whitespace.
const DEFTEST_RE = /\(deftest\s+(\S+)/g;

let srcDeftests = 0;
let extractedDeftests = 0;
const missingByFile = [];

for (const file of walk(repo)) {
  const src = readFileSync(file, 'utf8');

  // Ground-truth deftest names from raw source. Strip BOTH block comments
  // (`#| … |#`, nestable) and line comments (`;`-to-EOL) first, so a
  // commented-out `(deftest …)` doesn't inflate the count. Then skip
  // computed names — a deftest whose name begins with `,` / `(` / `` ` `` is
  // generated by an enclosing macro (e.g. `(deftest ,(make-name …) …)`) and
  // has no static symbol to extract.
  let cleaned = src;
  // Remove nested block comments by repeated innermost-first replacement.
  let prev;
  do { prev = cleaned; cleaned = cleaned.replace(/#\|(?:[^#|]|#(?!\|)|\|(?!#))*?\|#/g, ' '); }
  while (cleaned !== prev);
  cleaned = cleaned.replace(/;[^\n]*/g, '');
  const srcNames = new Set();
  let m;
  DEFTEST_RE.lastIndex = 0;
  while ((m = DEFTEST_RE.exec(cleaned)) !== null) {
    const name = m[1];
    if (/^[,(`]/.test(name)) continue; // computed / macro-generated name
    srcNames.add(name);
  }
  srcDeftests += srcNames.size;

  // Extracted names from the index pipeline.
  const ex = new LispExtractor(file, src);
  const r = ex.extract();
  const nodeNames = new Set(
    r.nodes.filter((n) => n.kind === 'function' || n.kind === 'method').map((n) => n.name)
  );

  let fileMissing = 0;
  for (const name of srcNames) {
    if (nodeNames.has(name)) extractedDeftests++;
    else { fileMissing++; }
  }
  if (fileMissing > 0) {
    missingByFile.push({ file: file.replace(repo, ''), missing: fileMissing, total: srcNames.size });
  }
}

console.log(`\nDeftest extraction validation — ${repo}`);
console.log(`  deftests in source:    ${srcDeftests}`);
console.log(`  extracted as nodes:    ${extractedDeftests}`);
console.log(`  coverage:              ${(100 * extractedDeftests / srcDeftests).toFixed(2)}%`);
if (missingByFile.length) {
  console.log(`\n  Files with missing deftests (top 15):`);
  missingByFile.sort((a, b) => b.missing - a.missing);
  for (const f of missingByFile.slice(0, 15)) {
    console.log(`    ${String(f.missing).padStart(4)} / ${String(f.total).padStart(4)}  ${f.file}`);
  }
} else {
  console.log(`\n  ✓ Every deftest in every file was extracted.`);
}
